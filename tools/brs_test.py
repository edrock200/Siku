"""Runs Siku's own BrightScript functions on the host, without the simulator or a Roku.

The idea is adapted from ManavA/silo-roku (AGPL-3.0) tools/brightscript.py: call a named
production function with JSON arguments and read its result back as JSON. Siku runs it in the
brs-cli that `npm install` already provides (brs-node, SceneGraph disabled with `-n`), so only
code that needs no SceneGraph node can be called this way: pure helpers, request builders and
the decisions that read `m` / `m.global` state, which a call can seed.

Python use (tests/ does this):

    from brs_test import call, calls
    call(["components/common/Utils.brs"], "Num_or", ["42"])            -> 42.0
    calls(FILES, [{"fn": "Num_or", "args": ["x", 5]},
                  {"fn": "Subs_autoChoice", "args": ["en"],
                   "m": {"subtitleTracks": [...], "watch": {...}},
                   "global": {"settings": {...}, "session": {...}, "prefs": {...}}}])
        -> [{"ok": True, "type": "Float", "value": 5.0}, {...}]

Each spec runs inside a try/catch in one brs-cli process, so a crash is reported for that call
(`ok: False, error: ...`) and the next call still runs. `m` keys a spec sets are removed before
the next spec, and `global` becomes `m.global` (a plain associative array: code that calls
`m.global.hasField` or observes fields cannot run here). Values come back through FormatJson, so
`invalid` reads as None; `type` is BrightScript's `Type()` of the result.

Command line:
    python3 tools/brs_test.py --file components/common/Utils.brs --fn Num_or --args '["12"]'
    python3 tools/brs_test.py --main tools/trickplay_test/run_tests.brs --file components/player/Trickplay.brs ...
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
BRS_CLI = os.environ.get("SIKU_BRS_CLI", os.path.join(ROOT, "node_modules", ".bin", "brs-cli"))
MARK = "BRS-TEST-RESULT"
DONE = "BRS-TEST-COMPLETE"
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class BrsError(RuntimeError):
    pass


def _stage(files, work):
    """Copies the production files into the brs-cli root under unique names."""
    names = []
    for i, f in enumerate(files):
        src = f if os.path.isabs(f) else os.path.join(ROOT, f)
        name = "f%02d_%s" % (i, os.path.basename(src))
        shutil.copy(src, os.path.join(work, name))
        names.append(name)
    return names


def run_main(files, timeout=300):
    """Runs brs-cli over `files` (the first must define Main) and returns its console text."""
    work = tempfile.mkdtemp(prefix="siku-brs-")
    try:
        names = _stage(files, work)
        out = subprocess.run([os.path.abspath(BRS_CLI), "-n", "-c", "0", "-r", "."] + names,
                             cwd=work, capture_output=True, text=True, timeout=timeout)
        return out.stdout + out.stderr
    finally:
        shutil.rmtree(work, ignore_errors=True)


def _driver(specs):
    lines = [
        "' Generated by tools/brs_test.py",
        "sub Main()",
        '    specs = ParseJson(ReadAsciiFile("pkg:/specs.json"))',
        "    m.brsTestKeys = []",
    ]
    for i, spec in enumerate(specs):
        fn = spec["fn"]
        if not IDENT.match(fn):
            raise ValueError("not a BrightScript identifier: %r" % fn)
        argc = len(spec.get("args", []))
        call_args = ", ".join("a[%d]" % k for k in range(argc))
        call = "%s(%s)" % (fn, call_args)
        lines += [
            "    BrsTest_prepare(specs[%d])" % i,
            "    a = specs[%d].args" % i,
            "    if a = invalid then a = []",
            "    try",
        ]
        if spec.get("sub"):
            lines += ["        %s" % call, "        BrsTest_emit(%d, invalid)" % i]
        else:
            lines += ["        r = %s" % call, "        BrsTest_emit(%d, r)" % i]
        lines += [
            "    catch e",
            '        print "%s %d ERR " + BrsTest_errorText(e)' % (MARK, i),
            "    end try",
        ]
    lines += [
        '    print "%s"' % DONE,
        "end sub",
        "",
        "sub BrsTest_prepare(spec as object)",
        "    for each k in m.brsTestKeys",
        "        m.Delete(k)",
        "    end for",
        "    m.brsTestKeys = []",
        "    if spec.m <> invalid then",
        "        for each k in spec.m",
        "            m[k] = spec.m[k]",
        "            m.brsTestKeys.Push(k)",
        "        end for",
        "    end if",
        "    g = spec.global",
        "    if g = invalid then g = {}",
        "    m.global = g",
        "end sub",
        "",
        "sub BrsTest_emit(i as integer, r as dynamic)",
        '    j = ""',
        "    if r = invalid then",
        '        j = "null"',
        "    else",
        "        j = FormatJson(r)",
        "    end if",
        '    print "%s " + i.ToStr() + " OK " + Type(r) + " " + j' % MARK,
        "end sub",
        "",
        "function BrsTest_errorText(e as dynamic) as string",
        '    if e = invalid then return "error"',
        '    if Type(e) = "roAssociativeArray" and e.message <> invalid then return e.message',
        '    return "error"',
        "end function",
    ]
    return "\n".join(lines) + "\n"


def calls(files, specs, timeout=300):
    """Runs every spec in one brs-cli process; returns one result dict per spec."""
    work = tempfile.mkdtemp(prefix="siku-brs-")
    try:
        names = _stage(files, work)
        with open(os.path.join(work, "specs.json"), "w", encoding="utf-8") as fh:
            json.dump([{"args": s.get("args", []), "m": s.get("m"), "global": s.get("global")} for s in specs], fh)
        with open(os.path.join(work, "brs_test_main.brs"), "w", encoding="utf-8") as fh:
            fh.write(_driver(specs))
        out = subprocess.run([os.path.abspath(BRS_CLI), "-n", "-c", "0", "-r", ".", "brs_test_main.brs"] + names,
                             cwd=work, capture_output=True, text=True, timeout=timeout)
        text = out.stdout + out.stderr
    finally:
        shutil.rmtree(work, ignore_errors=True)
    results = [None] * len(specs)
    for line in text.splitlines():
        if not line.startswith(MARK + " "):
            continue
        parts = line.split(" ", 4)
        idx = int(parts[1])
        if parts[2] == "ERR":
            results[idx] = {"ok": False, "error": line.split(" ERR ", 1)[1]}
            continue
        typ = parts[3]
        raw = parts[4] if len(parts) > 4 else ""
        try:
            value = json.loads(raw) if raw else None
        except ValueError:
            value = raw
        results[idx] = {"ok": True, "type": typ, "value": value}
    if DONE not in text or any(r is None for r in results):
        raise BrsError("brs-cli did not finish every call:\n" + text[-4000:])
    return results


def call(files, fn, args=(), m=None, global_=None):
    """One call; returns the value, or raises BrsError when the BrightScript code threw."""
    r = calls(files, [{"fn": fn, "args": list(args), "m": m, "global": global_}])[0]
    if not r["ok"]:
        raise BrsError("%s threw: %s" % (fn, r["error"]))
    return r["value"]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--file", action="append", default=[], help="production .brs file (repeat)")
    ap.add_argument("--fn", help="function to call")
    ap.add_argument("--args", default="[]", help="JSON array of arguments")
    ap.add_argument("--m", default=None, help="JSON object assigned into m before the call")
    ap.add_argument("--global", dest="glob", default=None, help="JSON object used as m.global")
    ap.add_argument("--main", help="run this .brs (with Main) together with --file instead of --fn")
    a = ap.parse_args()
    if a.main:
        sys.stdout.write(run_main([a.main] + a.file))
        return
    if not a.fn:
        ap.error("--fn or --main is required")
    spec = {"fn": a.fn, "args": json.loads(a.args),
            "m": json.loads(a.m) if a.m else None, "global": json.loads(a.glob) if a.glob else None}
    print(json.dumps(calls(a.file, [spec])[0], indent=2))


if __name__ == "__main__":
    main()
